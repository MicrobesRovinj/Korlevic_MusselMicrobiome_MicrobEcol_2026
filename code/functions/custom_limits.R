#################################################################################################################
# custom_limits.R
#
# Function to set custom axis limits.
#
#################################################################################################################

custom_limits <- function(x) {
  m <- max(x, na.rm = TRUE)
  if (m > 10    && m <= 20)    c(0, 20) else
  if (m > 20    && m <= 40)    c(0, 40) else
  if (m > 40    && m <= 60)    c(0, 60) else
  if (m > 60    && m <= 80)    c(0, 80) else
  if (m > 80    && m <= 100)   c(0, 100) else
  if (m > 100   && m <= 200)   c(0, 200) else
  if (m > 200   && m <= 600)   c(0, 600) else
  if (m > 600   && m <= 800)   c(0, 800) else
  if (m > 800   && m <= 1000)  c(0, 1000) else
  if (m > 1000  && m <= 1200)  c(0, 1200) else
  if (m > 1200  && m <= 2000)  c(0, 2000) else
  if (m > 2000  && m <= 2500)  c(0, 2500) else
  if (m > 2500  && m <= 5000)  c(0, 5000) else
  if (m > 5000  && m <= 8000)  c(0, 8000) else
  if (m > 8000  && m <= 10000) c(0, 10000) else
  if (m > 10000 && m <= 15000) c(0, 15000) else
  if (m > 15000 && m <= 20000) c(0, 20000) else
  if (m > 20000 && m <= 25000) c(0, 25000) else
  if (m > 25000 && m <= 35000) c(0, 35000) else
  if (m > 35000 && m <= 40000) c(0, 40000) else
  if (m > 40000 && m <= 75000) c(0, 75000) else
  if (m > 75000)               c(0, 100000) else
    numeric(length = 0)
}

